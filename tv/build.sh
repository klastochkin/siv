#!/bin/bash
# Package the SIV TV Tizen web app as a .wgt.
#
#   tv/build.sh [--server http://192.168.1.50:8080] [--token TOKEN] [--profile NAME] [--out PATH]
#
# --server/--token bake defaults into js/config.js so the TV opens straight into the
# library (handy with an arrow-only remote). Users can still change them in Settings.
#
# With the Tizen CLI installed (Tizen Studio), the package is signed with the given
# security profile and can be installed on a TV in Developer Mode. Without it, an
# unsigned .wgt is produced for inspection only — TVs refuse unsigned packages.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
STAGE="$PROJECT_DIR/.build/tv-stage"
OUT="$PROJECT_DIR/.build/tv/SIVTV.wgt"
SERVER=""
TOKEN=""
PROFILE="${TIZEN_PROFILE:-}"

while [ $# -gt 0 ]; do
    case "$1" in
        --server) SERVER="$2"; shift 2 ;;
        --token) TOKEN="$2"; shift 2 ;;
        --profile) PROFILE="$2"; shift 2 ;;
        --out) OUT="$2"; shift 2 ;;
        -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
        *) echo "Unknown option: $1" >&2; exit 2 ;;
    esac
done

js_string() {
    # Escape for a single-quoted JS string literal.
    printf "%s" "$1" | sed -e "s/\\\\/\\\\\\\\/g" -e "s/'/\\\\'/g"
}

find_tizen() {
    if command -v tizen >/dev/null 2>&1; then command -v tizen; return; fi
    for candidate in "${TIZEN_SDK_PATH:-$HOME/tizen-sdk}/tools/ide/bin/tizen" "$HOME/tizen-studio/tools/ide/bin/tizen" "/Applications/tizen-studio/tools/ide/bin/tizen"; do
        if [ -x "$candidate" ]; then echo "$candidate"; return; fi
    done
}

echo "Staging TV app..."
rm -rf "$STAGE"
mkdir -p "$STAGE" "$(dirname "$OUT")"
cp "$SCRIPT_DIR/config.xml" "$SCRIPT_DIR/index.html" "$SCRIPT_DIR/icon.png" "$STAGE/"
cp -R "$SCRIPT_DIR/css" "$SCRIPT_DIR/js" "$STAGE/"

if [ -n "$SERVER" ] || [ -n "$TOKEN" ]; then
    cat > "$STAGE/js/config.js" <<EOF
/* Generated by tv/build.sh */
window.SIV_CONFIG = {
  serverUrl: '$(js_string "$SERVER")',
  token: '$(js_string "$TOKEN")'
};
EOF
    echo "  default server: ${SERVER:-<none>}${TOKEN:+ (with token)}"
fi

if command -v xmllint >/dev/null 2>&1; then
    xmllint --noout "$STAGE/config.xml"
fi
if command -v node >/dev/null 2>&1; then
    for f in "$STAGE"/js/*.js; do node --check "$f"; done
fi

TIZEN="$(find_tizen || true)"
rm -f "$OUT"
if [ -n "$TIZEN" ]; then
    echo "Signing with Tizen CLI ($TIZEN)${PROFILE:+, profile $PROFILE}..."
    if [ -n "$PROFILE" ]; then
        "$TIZEN" package -t wgt -s "$PROFILE" -- "$STAGE"
    else
        "$TIZEN" package -t wgt -- "$STAGE"
    fi
    mv "$STAGE"/*.wgt "$OUT"
    echo "✅ Signed package: $OUT"
else
    (cd "$STAGE" && zip -qr -X "$OUT" .)
    echo "⚠️  Tizen CLI not found — wrote UNSIGNED package: $OUT"
    echo "   Install Tizen Studio + a Samsung certificate profile, then rerun to get an installable .wgt."
fi
